%% Single-site DMFT for the Emery (three-band Hubbard) model, U_d AND U_p
% Oxygens kept explicitly; local self-energy Sigma = diag(SEd, SEp, SEp).
% Two impurity problems per DMFT iteration (p_x and p_y are equivalent, one O solve):
%   Cu impurity: level ed - mu,          interaction U_d,  hybridization Gamma_d
%   O  impurity: level ep - 2tpp - mu,   interaction U_p,  hybridization Gamma_p
% Lattice step (emery_lattice_iqt.m, IQT integrator), z = w + i*etaLat + mu,
% with Sigma_p -> Sigma_p + SEeta(w) (causal broadening, lattice step only):
%   g(k,z) = [z - H(k) - Sigma]^{-1} (3x3),   G_a = <g_aa>_k
%   F_a = <[V g]_aa>_k = zeta_a G_a - 1,       Delta_a = F_a/G_a   (asymmetric estimator)
%   zeta_d = z - ed - SEd,   zeta_p = z - (ep - 2tpp) - SEp
% Tails: int Gamma_d = 4tpd^2 = 16,  int Gamma_p = 2tpd^2 + 4tpp^2 + 2tpp2^2 = 12.08.
% U_p = 0 must reproduce Ex_single_site_Emery.m (Gamma_d identical, SEp = 0).
%
% Double counting: the solver's self-energy has the high-frequency limit U*n/2
% the full Hartree shift U_p n_p/2 on O is
% generated by the solver and NOT subtracted.
% The O level is therefore ep - 2tpp (+ epDC, default 0). Choose epDC ~= 0 only if you
% take ep from a calculation that already contains the static O Hartree
% term. Bu putting in a finite epDC=-Up, we get rid of the hartree shift. 


clear
num_threads_SL(8);

%% Step 1: Model parameters (Sordi et al., PRB 111, 045117) and initial hybridizations 

Ud = 12;       % Cu interaction
Up = 0;        % O interaction (Up = 0: check against the Cu-only code)
T  = 0.05;
mu = 10;


P = struct('ed',0,'ep',2.8,'tpd',2,'tpp',1,'tpp2',0.2);
epDC = -Up;                   % optional static shift of the O level (double counting)
P.ep = P.ep + epDC;         % used consistently in the lattice step and in the O impurity
ept  = P.ep - 2*P.tpp;      % local O level (O impurity level is ept - mu)


% Causal two-pole broadening, added to SEp in the lattice step only (Kramers-Kronig exact):
%   SEeta(z) = etamx*wb*z/((z+i*wc)(z+i*wb)),   -Im SEeta = 0 at w = 0, ~etamx for wc << |w| << wb, ~1/w^2 beyond
eta0   = 0.02;    % only for the starting hybridizations (emery_startHyb_iqt)
etamx  = 0.3;  wc = 5;  wb = 20;
SEeta  = @(w) etamx*wb*w(:)./((w(:)+1i*wc).*(w(:)+1i*wb));

%  SEeta  = @(w) -1i*(eta0+etamx) - etamx*wc./(w(:) + 1i*wc);  % use in
%  case of emergencies only, where SEp cannot resolve the oxygen peak on
%  the NRG grid well.
etaLat = 1e-6;   % IQT regulator only



% Starting hybridizations (only for Nrun == 0), chosen separately for Cu and O
% (emery_startHyb.m): 'metallic', 'hubbardI' or 'hartree'
startD = 'hubbardI';   % Cu
startP = 'hartree';    % O
mu0    = mu;           % reference mu for 'metallic'
Gamma0 = [0.5, 0.5];   % [Cu, O] broadening for 'hartree'

Nrun = 0;

fname = @(n) [go('mu'),'/DMFT/Emery_code/Emery_IQT_implementation/Emery_two_impurity_single_site/Emery_twoimp_Ud_',num2str(Ud), ...
              '_Up_',num2str(Up),'_mu_',num2str(mu),'_T_',num2str(T),'_ep_',num2str(P.ep),'_epDC_',num2str(epDC),'_tpd_',num2str(P.tpd), ...
              '_tpp2_',num2str(P.tpp2),'_',startD,'_',startP,'_',num2str(n),'_IQT_SEeta.mat'];

if Nrun == 0

   ocont = getAcont(0,0,0,0);

   % Cu first (O self-energy 0), then O with the Cu starting self-energy;
   % both Gammas are taken from the last lattice step, Sigma = diag(SEd0, SEp0, SEp0)
   [~,SEd0] = emery_startHyb_iqt(ocont,mu,P,Ud,T,startD,'d','eta',eta0, ...
                             'mu0',mu0,'Gamma0',Gamma0(1));
   [~,SEp0,~,Rho0] = emery_startHyb_iqt(ocont,mu,P,Up,T,startP,'p','eta',eta0, ...
                             'mu0',mu0,'Gamma0',Gamma0(2),'SEother',SEd0);
   Rhoin_d = Rho0(:,1);
   Rhoin_p = Rho0(:,2);
   RhoV2_d_arr = [];  RhoV2_p_arr = [];
   nd = [];  np = [];  Wd = [];  Wp = []; tIter = []; logNRG = {};

else
   load(fname(Nrun-1),'ocont','Rhoin_d','Rhoin_p');
   Rhoin_d = Rhoin_d(:,end);  Rhoin_p = Rhoin_p(:,end);
   RhoV2_d_arr = [];  RhoV2_p_arr = [];
   nd = [];  np = [];  Wd = [];  Wp = []; tIter = []; logNRG = {};
end

fprintf('tails: int Gamma_d = %.3f (4tpd^2 = %.3f), int Gamma_p = %.3f (%.3f)\n', ...
        trapz(ocont,Rhoin_d(:,end)), 4*P.tpd^2, trapz(ocont,Rhoin_p(:,end)), ...
        2*P.tpd^2 + 4*P.tpp^2 + 2*P.tpp2^2);

% impurity hamiltonians (same symmetries; only U and the level differ)
[Hmu_d,HU_d,~,A0_d,FF_d,ZF_d,~,~,NF_d] = SIAM('Acharge,SU2spin',Ud,mu,P.ed,'-iso2HU');
[Hmu_p,HU_p,~,A0_p,FF_p,ZF_p,~,~,NF_p] = SIAM('Acharge,SU2spin',Up,mu,ept, '-iso2HU');


nrgdata_d = [getenv('SCRATCH_DIR'),'/Cu/'];   % separate folders: the two NRG runs
nrgdata_p = [getenv('SCRATCH_DIR'),'/O/'];    % must not overwrite each other

if ~exist(nrgdata_d,'dir')
    mkdir(nrgdata_d); 
end

if ~exist(nrgdata_p,'dir')
    mkdir(nrgdata_p); 
end

%% Step 2: Impurity hamiltonians and NRG parameters

Lambda  = 2;
nz      = 2;

Nkeep   = 1000;
NKEEP   = 3*Nkeep*ones(1,3);
Etrunc  = 10;
dz      = 1e-4/nz;
minRho  = 0;      % Do not clip off the edges of the hybridization, instead, fix a large window of [-Emax,+Emax]
minTE   = 1e-3;   % tolerence level in doZLD; if hybridization weight inside an interval is less than minTE, the interval is merged with its's neighbor
Emax    = 50;     % fixed outer boundary of the discretization grid (beyond all bands, Cu and O)
Emin    = 1e-12;  % inner edge of the discretization grid
Nchain  = ceil(-2*log(T/(100*Emax))/log(Lambda)) + 5;   % chain starts at the grid top, fixed for all iterations and
                                                        % both impurities; extends 2 decades below T for good measure
fprintf('Nchain = %d (Emax = %g)\n', Nchain, Emax);

% convergence: normalized Wasserstein-1 distance between input and output Gamma,
% for BOTH impurities below tolW for Ncons consecutive iterations
tolW  = 5e-3;
Ncons = 3;
W1 = @(w,a,b) trapz(w, abs(cumtrapz(w,a)/trapz(w,a) - cumtrapz(w,b)/trapz(w,b)));


%% Step 2.1: parallel pool: Cu and O impurity solves run simultaneously

c = parcluster('Processes');
c.NumThreads = 4;                             % MATLAB threads per worker
pool = gcp('nocreate');
if isempty(pool), pool = parpool(c,2); end
wait(parfevalOnAll(pool,@num_threads_SL,0,4));      % QSpace threads per worker (8 split in two)
wait(parfevalOnAll(pool,@setenv,0,'SCRATCH_DIR',getenv('SCRATCH_DIR')));
disp(fetchOutputs(parfevalOnAll(pool,@num_threads_SL,1)));   % check: should print 4 and 4

clear c

%% Step 3: DMFT self-consistency cycle (fixed mu)

N = 100;
Niter = 0;
iscvg = false;

while size(Rhoin_d,2) < N

    tLoop = tic;
    if iscvg
        disp('Convergence criteria met, exiting DMFT loop')
        break
    end


    % Step 3.1: the two NRG impurity solves, in parallel
    optsNRG = {'numCorr',3,'Nchain',Nchain, ...
       'doZLD',{'emin',Emin,'emax',Emax,'minrho',minRho,'minTE',minTE,'dz',dz}, ...
       'NRG_SL',{'Etrunc',Etrunc,'NKEEP',NKEEP},'SEtrick',{'iSEmax',-1e-8}};
    fd = parfeval(pool,@impSE,3,Hmu_d,HU_d,A0_d,FF_d,ZF_d,Rhoin_d(:,end),T,Lambda,nz,Nkeep,nrgdata_d,optsNRG{:});
    fp = parfeval(pool,@impSE,3,Hmu_p,HU_p,A0_p,FF_p,ZF_p,Rhoin_p(:,end),T,Lambda,nz,Nkeep,nrgdata_p,optsNRG{:});
    [ocont,SEd,nrgdataz_d] = fetchOutputs(fd);
    [ocont,SEp,nrgdataz_p] = fetchOutputs(fp);
    
    logNRG{Niter+1} = {fd.Diary, fp.Diary};   % saving logs of NRG_SL, get_FDM, Get_Adisc for both solvers

    clear fd fp


    nd = cat(2,nd,getEpVal(nrgdataz_d,NF_d));   % <n_d>, impurity
    np = cat(2,np,getEpVal(nrgdataz_p,NF_p));   % <n_p> per O orbital, impurity

    % Step 3.2: lattice step with Sigma = diag(SEd, SEp, SEp)
    [RhoV2,~,G] = emery_lattice_iqt(ocont,mu,P,SEd,SEp(:)+SEeta(ocont),'eta',etaLat);
    RhoV2_d_arr = cat(2,RhoV2_d_arr,real(RhoV2(:,1)));
    RhoV2_p_arr = cat(2,RhoV2_p_arr,real(RhoV2(:,2)));

    % Step 3.3: convergence measure (input of this iteration vs lattice output)
    Wd = cat(2,Wd,W1(ocont(:),Rhoin_d(:,end),RhoV2_d_arr(:,end)));
    Wp = cat(2,Wp,W1(ocont(:),Rhoin_p(:,end),RhoV2_p_arr(:,end)));
    fprintf('iter %d: nd = %.4f, np = %.4f, ntot = %.4f | W1_d = %.2e, W1_p = %.2e\n', ...
            Niter+1, nd(end), np(end), nd(end)+2*np(end), Wd(end), Wp(end));
    if numel(Wd) >= Ncons
        iscvg = all(Wd(end-Ncons+1:end) < tolW) && all(Wp(end-Ncons+1:end) < tolW);
    end

    % Step 3.4: update both hybridizations (mixing only; convergence decided above)
    [~,Rhoin_d_new] = updateHyb(Rhoin_d,RhoV2_d_arr,2,'cvgth',0,'Broyden',2,'amix',0.5);
    [~,Rhoin_p_new] = updateHyb(Rhoin_p,RhoV2_p_arr,2,'cvgth',0,'Broyden',2,'amix',0.5);
    Rhoin_d = cat(2,Rhoin_d,max(Rhoin_d_new,0));
    Rhoin_p = cat(2,Rhoin_p,max(Rhoin_p_new,0));

    save(fname(Nrun),'-v7.3');

    tIter = cat(2,tIter,toc(tLoop));                          
    save(fname(Nrun),'tIter','-append');
    Niter = Niter+1;
    disp(['Finished iteration number:',num2str(Niter),' (',num2str(tIter(end),'%.1f'),' s)']);
    %keyboard;
end

%% Step 4: Occupations from the converged lattice G (real axis), SEeta removed from O

Gp_phys = 1./(1./G(:,2) + SEeta(ocont));        % local O Green's function with the physical SEp
Wl = 25;  wf = (-Wl:1e-3:Wl).';  ff = 1./(exp(wf/T)+1);
Ad = interp1(ocont(:), -imag(G(:,1))/pi, wf, 'linear');
Ap = interp1(ocont(:), -imag(Gp_phys)/pi, wf, 'linear');
nd_latt = 2*trapz(wf, ff.*Ad);   np_latt = 2*trapz(wf, ff.*Ap);   ntot = nd_latt + 2*np_latt;
fprintf('mu = %.4f: nd(imp) = %.4f, nd(latt) = %.4f | np(imp) = %.4f, np(latt) = %.4f | ntot = %.4f\n', ...
        mu, nd(end), nd_latt, np(end), np_latt, ntot);

%% Step 5 (optional): spectral sum rules
Atot = Ad + 2*Ap;
fprintf('int Ad = %.4f, int Ap = %.4f, int Atot = %.4f (should be ~1, ~1, ~3)\n', ...
        trapz(wf,Ad), trapz(wf,Ap), trapz(wf,Atot));

